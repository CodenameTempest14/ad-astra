// Generates design/DESIGN.md from design/themes/themes.json so the documented tokens and their
// contrast ratios can never drift from the themes the checker verifies.
// Usage (repo root):  node tools/design-md.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(await readFile(path.join(root, 'design', 'themes', 'themes.json'), 'utf8'));

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => { const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x); return (hi + 0.05) / (lo + 0.05); };
const fmt = (r) => r.toFixed(2) + ':1';
const mark = (r, min) => (r >= min ? '✓' : '✗ below ' + min);

const T = cfg.thresholds;
const out = [];
const w = (...l) => out.push(...l);

w('<!-- GENERATED by tools/design-md.mjs from design/themes/themes.json. Do not edit by hand: change themes.json (or the script) and run `node tools/design-md.mjs`. -->',
  '# Ad Astra: Design Tokens and UI Usage Rules', '',
  'Single reference for how Ad Astra looks. The colours below are the values in `design/themes/themes.json`; every contrast ratio is computed from them by this script, and `npm run theme-check` (tests/ui-visual) verifies them on real template pages (text ≥ 4.5:1, large text ≥ 3:1, non-text ≥ 3:1).', '',
  '## 1. Rules', '',
  '1. **Semantic colours only.** UI code uses `primary`, `secondary`, `success`, `warning`, `danger`, `info` and the surface/text tokens. Never a literal hex, and never Tabler\'s demo palette (`btn-yellow`, `text-red`, `bg-azure-lt`).',
  '2. **Every theme must work.** A component is not done until it passes in all four themes (D-020). Colour is never the only signal: pair it with an icon or text (errors, pass/fail, flags).',
  '3. **Ad Astra branding overrides the template** (colours, logo, fonts); the template supplies layout and structure only (MASTER-PLAN §3).',
  '4. **Templates first.** No page, section or component without an Approved entry in `design/TEMPLATE_REGISTRY.md`.', '');

w('## 2. Themes', '', '| Theme | Base | Monaco theme | Purpose |', '|---|---|---|---|');
for (const [id, t] of Object.entries(cfg.themes)) w(`| \`${id}\` (${t.label}) | ${t.base} | \`${t.monacoTheme}\` | ${t.purpose} |`);
w('', `Default theme: \`${cfg.default}\`.`, '');

w('## 3. Colour tokens', '');
for (const [id, t] of Object.entries(cfg.themes)) {
  const v = t.vars;
  const bodyBg = v['--tblr-body-bg'], surface = v['--tblr-bg-surface'];
  w(`### ${t.label} (\`${id}\`)`, '', '**Surfaces and text** (contrast measured on the page background and on a card surface):', '',
    '| Token | Tabler variable | Value | On page bg | On surface | Needs |', '|---|---|---|---|---|---|');
  const textRows = [
    ['text.body', '--tblr-body-color'], ['text.emphasis', '--tblr-emphasis-color'], ['text.secondary', '--tblr-secondary-color'],
    ['text.tertiary', '--tblr-tertiary-color'], ['text.muted', '--tblr-muted'], ['text.link', '--tblr-link-color'], ['text.link-hover', '--tblr-link-hover-color'],
  ];
  for (const [name, key] of textRows) {
    if (!v[key]) continue;
    const a = ratio(v[key], bodyBg), b = ratio(v[key], surface);
    w(`| \`${name}\` | \`${key}\` | \`${v[key]}\` | ${fmt(a)} ${mark(a, T.normalText)} | ${fmt(b)} ${mark(b, T.normalText)} | ${T.normalText}:1 |`);
  }
  for (const [name, key] of [['surface.page', '--tblr-body-bg'], ['surface.card', '--tblr-bg-surface'], ['surface.sunken', '--tblr-bg-surface-secondary'], ['surface.raised', '--tblr-bg-surface-tertiary'], ['border.default', '--tblr-border-color']]) {
    if (v[key]) w(`| \`${name}\` | \`${key}\` | \`${v[key]}\` | n/a | n/a | decorative |`);
  }
  for (const [name, key] of [['control.border', '--aa-control-border'], ['focus.ring', '--aa-focus']]) {
    const a = ratio(v[key], bodyBg), b = ratio(v[key], surface);
    w(`| \`${name}\` | \`${key}\` | \`${v[key]}\` | ${fmt(a)} ${mark(a, T.nonText)} | ${fmt(b)} ${mark(b, T.nonText)} | ${T.nonText}:1 (non-text) |`);
  }
  w('', '**Semantic colours** (fill with its foreground text; and the fill used as text or an icon on the page):', '',
    '| Token | Fill | Foreground | Text on fill | Fill on page bg | Fill on surface |', '|---|---|---|---|---|---|');
  for (const [name, { fill, fg }] of Object.entries(t.semantic)) {
    const a = ratio(fg, fill), b = ratio(fill, bodyBg), c = ratio(fill, surface);
    w(`| \`${name}\` | \`${fill}\` | \`${fg}\` | ${fmt(a)} ${mark(a, T.normalText)} | ${fmt(b)} ${mark(b, T.nonText)} | ${fmt(c)} ${mark(c, T.nonText)} |`);
  }
  w('');
}

w('## 4. Typography', '',
  '> **Owner to confirm** (fonts are a taste decision). Proposed defaults; nothing is downloaded until confirmed.', '',
  '| Role | Font | Fallback | Licence | Notes |', '|---|---|---|---|---|',
  '| UI text | **Inter** (variable, woff2, bundled in the app) | `Segoe UI`, `system-ui`, sans-serif | SIL OFL 1.1 | Bundled so Playwright screenshots render identically on every PC (MASTER-PLAN §3.5); the app is offline, so no CDN. |',
  '| Code, output, Monaco | **JetBrains Mono** (variable, woff2, bundled) | `Cascadia Mono`, `Consolas`, monospace | SIL OFL 1.1 | Clear `0/O` and `1/l/I`, which matters for students reading code and test output. |', '',
  'Both licences allow bundling; the licence text must ship with the fonts and be listed in `THIRD_PARTY_NOTICES.md` (P01-16). Tabler\'s own default is the system font stack (Segoe UI on Windows), which is the fallback if a bundled font fails to load.', '',
  '**Scale** (taken from the Tabler templates we adapt; base 14px, line-height 1.43):', '',
  '| Token | Size / line | Weight | Use |', '|---|---|---|---|',
  '| `type.page-title` | 20px / 28px | 600 | page heading (h1) |', '| `type.section-title` | 16px / 24px | 500 | card and section headings (h2) |',
  '| `type.label` | 12px / 16px | 500 | small headings, table headers (h3) |', '| `type.body` | 14px / 20px | 400 | all running text |',
  '| `type.code` | 14px / 20px | 400 | editor, console, test output |', '',
  'Never go below 12px. The editor font size is user-adjustable (student feature) and does not change these tokens.', '');

w('## 5. Spacing, radius, elevation, focus', '',
  '| Group | Tokens | Source |', '|---|---|---|',
  '| Spacing | 4 · 8 · 16 · 24 · 32 · 48 px (`space.1` to `space.6`); base unit 8px (`--tblr-spacer: 0.5rem`) | Tabler spacing utilities (`p-1` … `p-5`) |',
  '| Corner radius | `radius.sm` 4px (badges, small controls) · `radius.md` 6px (inputs, buttons, cards) · `radius.lg` 8px (modals, large panels) · `radius.pill` (status pills) | `--tblr-border-radius*` |',
  '| Elevation | `elevation.0` flat (cards on page) · `elevation.1` `--tblr-box-shadow-sm` (dropdowns) · `elevation.2` `--tblr-box-shadow` (popovers) · `elevation.3` `--tblr-box-shadow-lg` (modals). Dark themes rely on surface colour steps (`surface.card` → `surface.raised`) more than shadows. | Tabler shadows |',
  '| Focus ring | `outline: 2px solid var(--aa-focus); outline-offset: 2px` on every focusable element; never `outline: none`. Colour per theme in §3 (≥ 3:1). | `--aa-focus`, themes.json `extraCss` |',
  '| Control border | 1px `--aa-control-border` on inputs, selects, checkboxes, option cards (≥ 3:1 so a control is findable without relying on fill). | `--aa-control-border` |', '');

w('## 6. Mapping: Tabler variables → Ad Astra tokens', '',
  'Ad Astra code refers to the token (middle column); the theme engine (Phase 2, P02-14) writes the Tabler variable (left column) from `themes.json`, so adapted template markup keeps working unchanged.', '',
  '| Tabler variable | Ad Astra token | Where the value comes from |', '|---|---|---|',
  '| `--tblr-body-bg` | `surface.page` | themes.json `vars` |', '| `--tblr-bg-surface` | `surface.card` | themes.json `vars` |',
  '| `--tblr-bg-surface-secondary` | `surface.sunken` | themes.json `vars` |', '| `--tblr-bg-surface-tertiary` | `surface.raised` | themes.json `vars` |',
  '| `--tblr-border-color` (+ `-translucent`) | `border.default` | themes.json `vars` |',
  '| `--tblr-body-color` | `text.body` | themes.json `vars` |', '| `--tblr-emphasis-color` | `text.emphasis` | themes.json `vars` |',
  '| `--tblr-secondary-color`, `--tblr-tertiary-color`, `--tblr-muted` | `text.secondary`, `text.tertiary`, `text.muted` | themes.json `vars` |',
  '| `--tblr-link-color`, `--tblr-link-hover-color` | `text.link`, `text.link-hover` | themes.json `vars` |',
  '| `--tblr-primary` / `-rgb` / `-fg` (and secondary, success, warning, danger, info) | `color.<name>`, `color.<name>.fg` | themes.json `semantic` (expanded into the three variables) |',
  '| `.form-control` etc. `border-color` | `control.border` (`--aa-control-border`) | themes.json `vars` + `extraCss` rule |',
  '| `:focus-visible` outline | `focus.ring` (`--aa-focus`) | themes.json `vars` + `extraCss` rule |',
  '| Monaco editor theme | `monacoTheme` per theme (`vs-dark`, `vs`, `hc-black`, `hc-light`) | themes.json; custom Monaco token colours are a Phase 7 item |', '',
  'Tabler\'s fixed white text on solid buttons and alerts is replaced by the `-fg` variables and the `extraCss` rules in themes.json, because dark themes need dark text on bright fills.', '');

w('## 7. How to change a token', '',
  '1. Edit `design/themes/themes.json`.', '2. `node tools/design-md.mjs` (this file).', '3. `cd tests/ui-visual && npm run theme-check` must report 0 failures for text and non-text.', '4. Record the decision in `documentation/DECISIONS.md` if it changes the look the owner approved.', '');

await writeFile(path.join(root, 'design', 'DESIGN.md'), out.join('\n'));
console.log(`design/DESIGN.md written (${out.length} lines)`);
