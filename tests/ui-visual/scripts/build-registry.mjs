// Builds the template registry from design/templates/template-manifest.json:
//  - copies the approved candidate's images into <element>/approved/
//  - writes <element>/README.md (the template record: source, license, adopt/change, files)
//  - writes design/TEMPLATE_REGISTRY.md (one row per page/section/component)
// Approval is recorded in the manifest ("approved": "<candidate source>").
//
// Usage (from tests/ui-visual):  npm run registry
import { readFile, writeFile, mkdir, copyFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const designDir = path.join(repoRoot, 'design');
const templatesDir = path.join(designDir, 'templates');
const manifest = JSON.parse(await readFile(path.join(templatesDir, 'template-manifest.json'), 'utf8'));

let captureLog = [];
try { captureLog = JSON.parse(await readFile(path.join(templatesDir, 'capture-log.json'), 'utf8')); } catch { /* none yet */ }

const sourceOf = (candidate) => manifest.sources[candidate.sourceRef ?? candidate.source];
const rel = (p) => path.relative(path.dirname(p.from), p.to).replaceAll('\\', '/');
const rows = [];

for (const element of manifest.elements) {
  const elementDir = path.join(templatesDir, `${element.level}s`, element.id);
  const approvedCandidate = element.candidates.find((c) => c.source === element.approved);
  const approvedFiles = [];

  if (approvedCandidate) {
    const fromDir = path.join(elementDir, 'candidates', approvedCandidate.source);
    if (existsSync(fromDir)) {
      const toDir = path.join(elementDir, 'approved');
      await mkdir(toDir, { recursive: true });
      for (const file of await readdir(fromDir)) {
        await copyFile(path.join(fromDir, file), path.join(toDir, file));
        approvedFiles.push(`approved/${file}`);
      }
    }
  }

  const captures = captureLog.filter((e) => e.id === element.id);
  const captureProblems = captures.filter((e) => e.status !== 'OK');
  const status = !approvedCandidate ? 'Proposed'
    : approvedFiles.length === 0 ? 'Proposed (no image)'
    : captureProblems.some((e) => e.candidate === element.approved) ? 'Proposed (capture suspect)'
    : 'Approved';

  const source = approvedCandidate ? sourceOf(approvedCandidate) : null;
  const candidateLines = element.candidates.map((c) => {
    const s = sourceOf(c);
    const shots = c.captures.map((cap) => {
      const logged = captures.find((e) => e.candidate === c.source && e.state === cap.state);
      return `  - \`${cap.state}\` — ${cap.url}${cap.selector ? ` (element \`${cap.selector}\`)` : ''} — capture: ${logged?.status ?? 'not run'}`;
    }).join('\n');
    return `- **${c.source}**${c.source === element.approved ? ' ✅ approved' : ''} — ${s.name} (${s.license}, ${s.repo})\n${shots}`;
  }).join('\n');

  const templateMd = `<!-- GENERATED by tests/ui-visual/scripts/build-registry.mjs from design/templates/template-manifest.json. Edit the manifest, not this file. -->
# Template: ${element.name} (\`${element.id}\`)

| Field | Value |
|---|---|
| Level | ${element.level} |
| Built in | Phase ${element.phase} |
| Used by | ${element.usedBy} |
| Status | **${status}** |
| Approved source | ${source ? `${source.name} — ${source.home}` : '—'} |
| License | ${source ? source.license : '—'} |

## What we adopt
${element.adopt}

## What Ad Astra changes
${element.change}

Ad Astra branding (plan §1.1) always overrides template colours and logos.

## Candidates
${candidateLines}

## Approved images
${approvedFiles.length ? approvedFiles.map((f) => `- [${f}](${f})`).join('\n') : '_None yet._'}
`;
  await mkdir(elementDir, { recursive: true });
  await writeFile(path.join(elementDir, 'README.md'), templateMd);
  if (existsSync(path.join(elementDir, 'candidates'))) {
    await writeFile(path.join(elementDir, 'candidates', 'README.md'),
      `# Candidates for \`${element.id}\`\n\nShortlisted template captures, one folder per source. Not approved unless named in ../README.md.\nRe-capture: \`npm run capture-templates -- ${element.id}\` in tests/ui-visual.\n`);
    for (const c of element.candidates) {
      const dir = path.join(elementDir, 'candidates', c.source);
      if (!existsSync(dir)) continue;
      const s = sourceOf(c);
      const urls = c.captures.map((cap) => `- \`${cap.state}\`: ${cap.url}`).join('\n');
      await writeFile(path.join(dir, 'README.md'),
        `# Candidate \`${c.source}\` for \`${element.id}\`${c.source === element.approved ? ' (approved)' : ''}\n\n${s.name} — ${s.license} — ${s.repo}\n\nCaptured from:\n${urls}\n\nFile names: \`<state>__<theme>__<viewport>.png\`. Reference captures of public pages; nothing here is shipped in the product.\n`);
    }
  }
  if (approvedFiles.length) {
    await writeFile(path.join(elementDir, 'approved', 'README.md'),
      `# Approved template images for \`${element.id}\`\n\nCopied from \`candidates/${element.approved}/\` by build-registry.mjs. These are what Playwright passes compare against (plan §3.5). Never overwrite: a changed template goes in a new \`v2/\` folder.\n`);
  }

  const firstImage = approvedFiles[0]
    ? `[image](templates/${element.level}s/${element.id}/${approvedFiles[0]})` : '—';
  rows.push(`| \`${element.id}\` | ${element.level} | ${element.name} | P${element.phase} | ${source ? source.name.split(' (')[0] : '—'} | ${source?.license ?? '—'} | ${status} | ${firstImage} | — |`);
}

const order = { page: 0, section: 1, component: 2 };
const sorted = manifest.elements.map((e, i) => ({ e, row: rows[i] }))
  .sort((a, b) => order[a.e.level] - order[b.e.level] || a.e.phase - b.e.phase)
  .map((x) => x.row);

const registry = `<!-- GENERATED by tests/ui-visual/scripts/build-registry.mjs. Edit design/templates/template-manifest.json, then run \`npm run registry\` in tests/ui-visual. -->
# Template Registry

Every page, section and component in Ad Astra and its approved template (plan §3.3).
**Status flow:** Proposed → Approved → Implemented → Verified (Playwright pass, no Mismatch) → Baselined.
Implemented/Verified/Baselined are set during the build phases; the last column links the latest pass report.

| ID | Level | Name | Phase | Source | License | Status | Template image | Last visual pass |
|---|---|---|---|---|---|---|---|---|
${sorted.join('\n')}

**Totals:** ${manifest.elements.length} elements — ${rows.filter((r) => r.includes('| Approved |')).length} approved.
`;
await writeFile(path.join(designDir, 'TEMPLATE_REGISTRY.md'), registry);
console.log(`Registry written: ${manifest.elements.length} elements.`);
